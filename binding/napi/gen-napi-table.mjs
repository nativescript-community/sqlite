#!/usr/bin/env node
// Generates napi_dyn.h / napi_dyn.c from napi_symbols.txt: the Node-API functions the binding uses are
// looked up at runtime (dlsym) instead of linked, so the binding loads on every runtime and is simply
// inactive where napi_* does not exist (NativeScript <= 8). Update napi_symbols.txt with:
//   every napi_* function called by nssqlite_napi.c must be listed, one per line, sorted (a missing entry fails to
//   compile: the call would reference a real napi_* symbol and the iOS/Android link would break on NS 8).
//   Candidates: grep -o '\bnapi_[a-z0-9_]*(' nssqlite_napi.c | tr -d '(' | sort -u   (ignore napi_dyn_load)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = dirname(fileURLToPath(import.meta.url));
const syms = readFileSync(join(dir, 'napi_symbols.txt'), 'utf8').split('\n').map((s) => s.trim()).filter(Boolean);

const h = `/* Generated by gen-napi-table.mjs from napi_symbols.txt. Do not edit. */
#ifndef NAPI_DYN_H
#define NAPI_DYN_H

#include <node_api.h>

typedef struct NapiTable {
${syms.map((s) => `    __typeof__(${s})* p_${s};`).join('\n')}
} NapiTable;

extern NapiTable g_napi;

/* Resolves every function from the runtime. Returns 0 when all are available. */
int napi_dyn_load(void);

${syms.map((s) => `#define ${s} (g_napi.p_${s})`).join('\n')}

#endif
`;

const c = `/* Generated by gen-napi-table.mjs from napi_symbols.txt. Do not edit. */
#include <dlfcn.h>

#include <node_api.h>

#include "napi_dyn.h"

#undef napi_dyn_dummy
${syms.map((s) => `#undef ${s}`).join('\n')}

NapiTable g_napi;

static void* lookup(void* extra, const char* name) {
    void* p = dlsym(RTLD_DEFAULT, name);
    if (!p && extra) p = dlsym(extra, name);
    return p;
}

int napi_dyn_load(void) {
    if (g_napi.p_napi_module_register) return 0;
    /* Android loads the runtime library with local scope: look it up explicitly when the global scope misses */
    void* extra = dlopen("libNativeScript.so", RTLD_NOW | RTLD_NOLOAD);
    int missing = 0;
${syms.map((s) => `    *(void**)&g_napi.p_${s} = lookup(extra, "${s}");\n    if (!g_napi.p_${s}) missing++;`).join('\n')}
    return missing;
}
`;
writeFileSync(join(dir, 'napi_dyn.h'), h);
writeFileSync(join(dir, 'napi_dyn.c'), c);
console.log(`generated ${syms.length} entries`);
