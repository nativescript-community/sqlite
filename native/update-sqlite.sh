#!/bin/sh
# Pins another SQLite version for libsqlite.so (sqlite-shared-engine): downloads its amalgamation, records version, release
# year and checksum in native/sqlite-version.sh. Then run native/build-sqlite.sh.
# Usage: native/update-sqlite.sh <version> [year]     e.g. native/update-sqlite.sh 3.54.0
#   year defaults to the current year, then the previous one (sqlite.org files releases under their year).
#   SQLITE_ZIP=<file> uses a local amalgamation zip instead of downloading.
set -e
ROOT=$(cd "$(dirname "$0")/.." && pwd)
VERSION=${1:?usage: native/update-sqlite.sh <version> [year]}
NUM=$(echo "$VERSION" | awk -F. '{ printf "%d%02d%02d00", $1, $2, $3 }')
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
ZIP=${SQLITE_ZIP:-$TMP/amalgamation.zip}
YEAR=$2
if [ -z "$SQLITE_ZIP" ]; then
  THIS_YEAR=$(date +%Y)
  for candidate in ${YEAR:-$THIS_YEAR $((THIS_YEAR - 1))}; do
    if curl -fL -s -o "$ZIP" "https://www.sqlite.org/$candidate/sqlite-amalgamation-$NUM.zip"; then
      YEAR=$candidate
      break
    fi
  done
  [ -n "$YEAR" ] && [ -s "$ZIP" ] || { echo "update-sqlite: sqlite-amalgamation-$NUM.zip not found on sqlite.org" >&2; exit 1; }
fi
YEAR=${YEAR:-$(date +%Y)}
cat > "$ROOT/native/sqlite-version.sh" <<PINS
# The SQLite behind libsqlite.so (sqlite-shared-engine). Generated by native/update-sqlite.sh: do not edit by hand.
SQLITE_VERSION=$VERSION
SQLITE_YEAR=$YEAR
SQLITE_SHA256=$(shasum -a 256 "$ZIP" | cut -d' ' -f1)
PINS
cat "$ROOT/native/sqlite-version.sh"
